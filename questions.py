    if score <= 10:
        return {"level": "A1 (Beginner / مبتدی)", "course": "دوره فاندامنتال و پایه‌ای مکالمه"}
    elif score <= 18:
        return {"level": "A2 (Elementary / پیش‌متوسط)", "course": "دوره‌های Speak Now و مکالمه روزمره"}
